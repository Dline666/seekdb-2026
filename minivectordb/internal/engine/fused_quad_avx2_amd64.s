	VCVTDQ2PD X4, Y0
	// Transpose four row-major (m2,t2,s2,cRow) tuples into columns.
	MOVL 0(BX), CX
	SHLQ $5, CX
	VMOVUPD (R15)(CX*1), Y1
	MOVL 4(BX), CX
	SHLQ $5, CX
	VMOVUPD (R15)(CX*1), Y2
	MOVL 8(BX), CX
	SHLQ $5, CX
	VMOVUPD (R15)(CX*1), Y3
	MOVL 12(BX), CX
	SHLQ $5, CX
	VMOVUPD (R15)(CX*1), Y4
	VUNPCKLPD Y2, Y1, Y5
	VUNPCKHPD Y2, Y1, Y6
	VUNPCKLPD Y4, Y3, Y7
	VUNPCKHPD Y4, Y3, Y8
