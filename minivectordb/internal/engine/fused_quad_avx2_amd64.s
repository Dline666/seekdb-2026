	VPERM2F128 $0x20, Y8, Y6, Y2
	VPERM2F128 $0x31, Y7, Y5, Y3
	VPERM2F128 $0x31, Y8, Y6, Y4
	VMULPD Y12, Y1, Y1
	VADDPD Y13, Y1, Y1
	VADDPD Y4, Y1, Y1
